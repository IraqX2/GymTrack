-- Apply once in the Supabase SQL Editor before deploying this branch.
-- This migration is required because Vercel startup deliberately does not run
-- SQLModel.metadata.create_all() against the hosted database.

CREATE TABLE IF NOT EXISTS public.workout_progress (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id integer NOT NULL
        REFERENCES public.workout_assignment(id) ON DELETE CASCADE,
    trainer_id integer NOT NULL
        REFERENCES public.trainer(id) ON DELETE CASCADE,
    status varchar(20) NOT NULL DEFAULT 'in_progress'
        CHECK (status IN ('in_progress', 'completed')),
    notes varchar(600) NOT NULL DEFAULT '',
    recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_workout_progress_assignment_id
    ON public.workout_progress (assignment_id);

CREATE INDEX IF NOT EXISTS ix_workout_progress_trainer_id
    ON public.workout_progress (trainer_id);

CREATE INDEX IF NOT EXISTS ix_workout_progress_recorded_at
    ON public.workout_progress (recorded_at);
