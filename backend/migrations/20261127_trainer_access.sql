-- GymTrack trainer-account linking, progress history and private-table hardening.
-- Apply to the GymTrack Supabase PostgreSQL project before deploying this branch.
ALTER TABLE public.trainer
    ADD COLUMN IF NOT EXISTS user_id BIGINT NULL REFERENCES public."user"(id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_trainer_user_id
    ON public.trainer (user_id)
    WHERE user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.trainer_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES public.workout_assignment(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES public.member(id) ON DELETE CASCADE,
    trainer_id BIGINT NOT NULL REFERENCES public.trainer(id) ON DELETE CASCADE,
    completion_percent INTEGER NOT NULL CHECK (completion_percent >= 0 AND completion_percent <= 100),
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    progress_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_trainer_progress_assignment_id
    ON public.trainer_progress (assignment_id);
CREATE INDEX IF NOT EXISTS ix_trainer_progress_member_id
    ON public.trainer_progress (member_id);
CREATE INDEX IF NOT EXISTS ix_trainer_progress_trainer_id
    ON public.trainer_progress (trainer_id);

-- The GymTrack web app uses FastAPI with a private PostgreSQL connection.
-- No browser client uses Supabase's anon/authenticated Data API roles.
-- Keep every public table private to those roles and enable RLS as a second
-- layer in case grants are introduced later. The FastAPI postgres role is the
-- database owner and continues to operate under its existing server controls.
DO $$
DECLARE
    target_table RECORD;
BEGIN
    FOR target_table IN
        SELECT schemaname, tablename
        FROM pg_tables
        WHERE schemaname = 'public'
    LOOP
        EXECUTE format(
            'ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY',
            target_table.schemaname,
            target_table.tablename
        );
    END LOOP;
END
$$;

REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
    REVOKE ALL ON TABLES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
    REVOKE ALL ON SEQUENCES FROM anon, authenticated;
